"use client";

import React, { useState, useEffect } from "react";
import { GeneratedReadingDocument } from "@/lib/reading-engine/types";

interface ReadingDocumentViewerProps {
  document: GeneratedReadingDocument;
  onRegenerate?: () => Promise<void>;
  isRegenerating?: boolean;
  onClose?: () => void;
  fullPageRoute?: boolean;
}

export default function ReadingDocumentViewer({
  document,
  onRegenerate,
  isRegenerating = false,
  onClose,
  fullPageRoute = false,
}: ReadingDocumentViewerProps) {
  const content = document.content;
  const [activeSection, setActiveSection] = useState<string>("overview");
  const [revealedAnswers, setRevealedAnswers] = useState<Record<string, boolean>>({});
  const [copiedCodeIndex, setCopiedCodeIndex] = useState<number | null>(null);

  // Accessibility States
  const [isSpeaking, setIsSpeaking] = useState(false);
  const [fontSize, setFontSize] = useState<"normal" | "large" | "xlarge">("normal");
  const [isHighContrast, setIsHighContrast] = useState(false);

  useEffect(() => {
    return () => {
      if (typeof window !== "undefined" && "speechSynthesis" in window) {
        window.speechSynthesis.cancel();
      }
    };
  }, []);

  const toggleSpeech = () => {
    if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
    if (isSpeaking) {
      window.speechSynthesis.cancel();
      setIsSpeaking(false);
    } else {
      const textToRead = `${content.title}. Introduction: ${content.introduction}. Core conceptual explanation: ${content.detailedConceptualExplanation}`;
      const utterance = new SpeechSynthesisUtterance(textToRead);
      utterance.rate = 0.95;
      utterance.onend = () => setIsSpeaking(false);
      utterance.onerror = () => setIsSpeaking(false);
      window.speechSynthesis.speak(utterance);
      setIsSpeaking(true);
    }
  };

  const toggleAnswer = (qId: string) => {
    setRevealedAnswers((prev) => ({ ...prev, [qId]: !prev[qId] }));
  };

  const handlePrint = () => {
    if (typeof window !== "undefined") {
      window.print();
    }
  };

  const copyCode = (code: string, idx: number) => {
    navigator.clipboard.writeText(code);
    setCopiedCodeIndex(idx);
    setTimeout(() => setCopiedCodeIndex(null), 2000);
  };

  const formattedDate = new Date(document.generatedAt).toLocaleDateString(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
  });

  return (
    <article
      className={`reading-monograph rounded-2xl border shadow-sm overflow-hidden flex flex-col print:border-none print:shadow-none print:rounded-none transition-all ${
        isHighContrast
          ? "bg-black text-white border-white"
          : "bg-surface-container-lowest text-on-surface border-surface-container-high/60"
      } ${
        fontSize === "large" ? "text-base" : fontSize === "xlarge" ? "text-lg" : "text-xs"
      }`}
    >
      {/* Document Attribution & Metadata Header */}
      <header className="p-4 sm:p-6 bg-surface-container-low border-b border-surface-container-high/60 flex flex-col gap-3 print:bg-white print:border-b-2 print:border-black">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2 flex-wrap">
            <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-primary/10 text-primary border border-primary/20">
              <span className="material-symbols-outlined text-sm">auto_stories</span>
              Pencill AI Generated Study Notes
            </span>
            <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-xs font-medium bg-surface-container text-on-surface-variant">
              <span className="material-symbols-outlined text-xs text-secondary">verified</span>
              Generated by Pencill Academic Engine
            </span>
            <span className="font-mono text-xs text-on-surface-variant">
              {document.generationModel}
            </span>
          </div>

          {/* Action Toolbar */}
          <div className="flex items-center gap-2 print:hidden">
            {/* Text to Speech Narration */}
            <button
              type="button"
              onClick={toggleSpeech}
              className={`inline-flex items-center gap-1 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all shadow-xs ${
                isSpeaking
                  ? "bg-secondary text-on-secondary animate-pulse"
                  : "bg-surface-container hover:bg-surface-container-high text-primary"
              }`}
              title={isSpeaking ? "Stop audio narration" : "Listen to audio narration"}
            >
              <span className="material-symbols-outlined text-sm">
                {isSpeaking ? "stop" : "volume_up"}
              </span>
              <span>{isSpeaking ? "Stop" : "Listen"}</span>
            </button>

            {/* Font Size Stepper */}
            <div className="flex items-center bg-surface-container rounded-lg p-0.5 border border-surface-container-high/60">
              <button
                type="button"
                onClick={() => setFontSize("normal")}
                className={`px-2 py-0.5 rounded text-[11px] font-bold ${fontSize === "normal" ? "bg-surface-container-lowest text-primary shadow-2xs" : "text-on-surface-variant"}`}
                title="Default text size"
              >
                A
              </button>
              <button
                type="button"
                onClick={() => setFontSize("large")}
                className={`px-2 py-0.5 rounded text-[11px] font-bold ${fontSize === "large" ? "bg-surface-container-lowest text-primary shadow-2xs" : "text-on-surface-variant"}`}
                title="Large text size"
              >
                A+
              </button>
              <button
                type="button"
                onClick={() => setFontSize("xlarge")}
                className={`px-2 py-0.5 rounded text-[11px] font-bold ${fontSize === "xlarge" ? "bg-surface-container-lowest text-primary shadow-2xs" : "text-on-surface-variant"}`}
                title="Extra large text size"
              >
                A++
              </button>
            </div>

            {/* High Contrast Mode Toggle */}
            <button
              type="button"
              onClick={() => setIsHighContrast(!isHighContrast)}
              className={`p-1.5 rounded-lg text-xs transition-colors ${
                isHighContrast
                  ? "bg-primary text-on-primary"
                  : "bg-surface-container hover:bg-surface-container-high text-on-surface-variant"
              }`}
              title="Toggle high contrast accessibility mode"
            >
              <span className="material-symbols-outlined text-sm">contrast</span>
            </button>

            <button
              type="button"
              onClick={handlePrint}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg bg-surface-container hover:bg-surface-container-high text-xs font-semibold text-primary transition-all shadow-xs"
              title="Print monograph or save as PDF"
            >
              <span className="material-symbols-outlined text-sm">print</span>
              <span>Print / PDF</span>
            </button>

            {onRegenerate && (
              <button
                type="button"
                onClick={onRegenerate}
                disabled={isRegenerating}
                className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg bg-surface-container hover:bg-surface-container-high text-xs font-semibold text-on-surface-variant transition-all disabled:opacity-50"
                title="Regenerate notes with Pencill AI"
              >
                <span className={`material-symbols-outlined text-sm ${isRegenerating ? "animate-spin" : ""}`}>
                  refresh
                </span>
                <span>{isRegenerating ? "Regenerating..." : "Regenerate"}</span>
              </button>
            )}

            {onClose && !fullPageRoute && (
              <button
                type="button"
                onClick={onClose}
                className="p-1.5 rounded-lg hover:bg-surface-container text-on-surface-variant transition-colors"
                title="Close reading view"
              >
                <span className="material-symbols-outlined text-lg">close</span>
              </button>
            )}
          </div>
        </div>

        <div className="space-y-1 pt-1">
          <h1 className="font-headline-lg text-2xl sm:text-3xl font-serif text-primary tracking-tight">
            {content.title}
          </h1>
          <div className="flex items-center gap-3 text-xs text-on-surface-variant flex-wrap">
            <span className="flex items-center gap-1 font-medium">
              <span className="material-symbols-outlined text-sm">schedule</span>
              {document.readingDurationMinutes} Min Read
            </span>
            <span>•</span>
            <span className="capitalize">{document.academicLevel} Level</span>
            <span>•</span>
            <span>Generated {formattedDate}</span>
          </div>
        </div>

        {/* Section Navigation Pills (Interactive in browser, hidden in print) */}
        <nav className="flex items-center gap-2 overflow-x-auto pb-1 pt-2 scrollbar-none print:hidden border-t border-surface-container-high/40 text-xs">
          {[
            { id: "overview", label: "Overview & Objectives" },
            { id: "conceptual", label: "Core Theory" },
            { id: "definitions", label: "Definitions" },
            { id: "steps", label: "Technique Breakdown" },
            { id: "misconceptions", label: "Common Pitfalls" },
            { id: "worked-examples", label: "Worked Problems" },
            { id: "assessment", label: "Self-Assessment" },
            { id: "summary", label: "Summary" },
          ].map((sec) => (
            <a
              key={sec.id}
              href={`#sec-${sec.id}`}
              onClick={() => setActiveSection(sec.id)}
              className={`px-2.5 py-1 rounded-md shrink-0 transition-colors font-medium ${
                activeSection === sec.id
                  ? "bg-primary text-on-primary font-semibold"
                  : "bg-surface-container text-on-surface-variant hover:text-primary"
              }`}
            >
              {sec.label}
            </a>
          ))}
        </nav>
      </header>

      {/* Main Document Body */}
      <div className="p-4 sm:p-8 space-y-8 font-body-lg text-on-surface max-w-4xl mx-auto leading-relaxed">
        {/* Section 1: Overview & Learning Objectives */}
        <section id="sec-overview" className="space-y-4">
          <div className="prose text-base sm:text-lg text-on-surface leading-relaxed">
            <p className="font-serif italic text-primary/90 border-l-4 border-primary pl-4 py-1 bg-surface-container-low/50 rounded-r-lg">
              {content.introduction}
            </p>
          </div>

          {/* Objectives Card */}
          <div className="p-4 rounded-xl bg-primary/5 border border-primary/20 space-y-2">
            <h3 className="font-label-lg text-sm font-semibold uppercase tracking-wider text-primary flex items-center gap-1.5">
              <span className="material-symbols-outlined text-base">flag</span>
              Learning Objectives
            </h3>
            <ul className="space-y-1.5">
              {content.learningObjectives.map((obj, i) => (
                <li key={i} className="flex items-start gap-2 text-sm text-on-surface">
                  <span className="material-symbols-outlined text-primary text-sm mt-0.5 shrink-0">
                    check_circle
                  </span>
                  <span>{obj}</span>
                </li>
              ))}
            </ul>
          </div>

          {/* Prerequisites if present */}
          {content.prerequisiteConcepts && content.prerequisiteConcepts.length > 0 && (
            <div className="flex items-center gap-2 flex-wrap text-xs text-on-surface-variant pt-1">
              <span className="font-semibold text-secondary flex items-center gap-1">
                <span className="material-symbols-outlined text-sm">school</span>
                Prerequisites:
              </span>
              {content.prerequisiteConcepts.map((pre, i) => (
                <span key={i} className="px-2 py-0.5 rounded bg-surface-container font-mono">
                  {pre}
                </span>
              ))}
            </div>
          )}
        </section>

        {/* Section 2: Detailed Conceptual Narrative */}
        <section id="sec-conceptual" className="space-y-3 pt-4 border-t border-surface-container-high/40">
          <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
            <span className="material-symbols-outlined text-secondary">psychology</span>
            Comprehensive Conceptual Framework
          </h2>
          <div className="text-on-surface leading-relaxed whitespace-pre-line text-sm sm:text-base space-y-4">
            {content.detailedConceptualExplanation}
          </div>
        </section>

        {/* Section 3: Important Definitions */}
        {content.importantDefinitions && content.importantDefinitions.length > 0 && (
          <section id="sec-definitions" className="space-y-3 pt-4 border-t border-surface-container-high/40">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
              <span className="material-symbols-outlined text-secondary">dictionary</span>
              Key Terms &amp; Definitions
            </h2>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {content.importantDefinitions.map((d, i) => (
                <div
                  key={i}
                  className="p-3.5 rounded-xl bg-surface-container-low border border-surface-container-high/60 space-y-1"
                >
                  <h4 className="font-label-lg text-sm font-bold text-primary font-mono">{d.term}</h4>
                  <p className="text-xs sm:text-sm text-on-surface leading-normal">{d.definition}</p>
                  {d.context && (
                    <p className="text-[11px] text-on-surface-variant italic pt-1">Context: {d.context}</p>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Section 4: Step-by-Step Breakdown */}
        {content.stepByStepExplanations && content.stepByStepExplanations.length > 0 && (
          <section id="sec-steps" className="space-y-4 pt-4 border-t border-surface-container-high/40">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
              <span className="material-symbols-outlined text-secondary">route</span>
              Methodology &amp; Step-by-Step Analysis
            </h2>
            <div className="space-y-3">
              {content.stepByStepExplanations.map((step, i) => (
                <div
                  key={i}
                  className="p-4 rounded-xl bg-surface-container-lowest border border-surface-container-high/60 space-y-2 relative pl-12"
                >
                  <div className="absolute left-3 top-4 w-7 h-7 rounded-full bg-primary text-on-primary font-bold text-xs flex items-center justify-center">
                    {step.stepNumber}
                  </div>
                  <h4 className="font-label-lg text-sm sm:text-base font-semibold text-primary">
                    {step.title}
                  </h4>
                  <p className="text-xs sm:text-sm text-on-surface leading-relaxed">
                    {step.explanation}
                  </p>
                  {step.codeOrFormula && (
                    <div className="mt-2 p-3 rounded-lg bg-surface-container-high/40 font-mono text-xs text-primary overflow-x-auto">
                      <code>{step.codeOrFormula}</code>
                    </div>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Section 5: Relevant Examples & Real-World Applications */}
        {((content.relevantExamples && content.relevantExamples.length > 0) ||
          (content.practicalApplications && content.practicalApplications.length > 0)) && (
          <section className="space-y-4 pt-4 border-t border-surface-container-high/40">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
              <span className="material-symbols-outlined text-secondary">lightbulb</span>
              Applied Scenarios &amp; Practical Applications
            </h2>

            {content.relevantExamples && content.relevantExamples.map((ex, i) => (
              <div
                key={i}
                className="p-4 rounded-xl bg-surface-container-low border border-surface-container-high/60 space-y-2"
              >
                <h4 className="font-label-lg text-sm sm:text-base font-semibold text-secondary flex items-center gap-1.5">
                  <span className="material-symbols-outlined text-base">biotech</span>
                  {ex.title}
                </h4>
                <div className="text-xs sm:text-sm space-y-1.5">
                  <p className="text-on-surface-variant font-medium">Scenario: {ex.scenario}</p>
                  <p className="text-on-surface">Analysis: {ex.solutionOrExplanation}</p>
                </div>
              </div>
            ))}

            {content.practicalApplications && content.practicalApplications.length > 0 && (
              <div className="p-3.5 rounded-xl bg-surface-container-high/20 border border-surface-container-high/40 space-y-1.5">
                <span className="font-label-sm text-xs font-semibold text-primary uppercase tracking-wider">
                  Industry &amp; Research Applications
                </span>
                <ul className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs sm:text-sm text-on-surface">
                  {content.practicalApplications.map((app, i) => (
                    <li key={i} className="flex items-start gap-1.5">
                      <span className="material-symbols-outlined text-secondary text-sm shrink-0 mt-0.5">
                        arrow_right
                      </span>
                      <span>{app}</span>
                    </li>
                  ))}
                </ul>
              </div>
            )}
          </section>
        )}

        {/* Section 6: Common Mistakes & Misconceptions */}
        {content.commonMistakesAndMisconceptions && content.commonMistakesAndMisconceptions.length > 0 && (
          <section id="sec-misconceptions" className="space-y-3 pt-4 border-t border-surface-container-high/40">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-error flex items-center gap-2">
              <span className="material-symbols-outlined text-error">warning</span>
              Common Pitfalls &amp; Misconceptions
            </h2>
            <div className="space-y-3">
              {content.commonMistakesAndMisconceptions.map((m, i) => (
                <div
                  key={i}
                  className="p-4 rounded-xl bg-error/5 border border-error/20 space-y-2"
                >
                  <div className="flex items-start gap-2 text-xs sm:text-sm font-semibold text-error">
                    <span className="material-symbols-outlined text-base shrink-0 mt-0.5">cancel</span>
                    <span>Misconception: &quot;{m.misconception}&quot;</span>
                  </div>
                  <div className="flex items-start gap-2 text-xs sm:text-sm text-on-surface pl-6">
                    <span className="font-bold text-primary shrink-0">Correction:</span>
                    <span>{m.correction}</span>
                  </div>
                  {m.whyItMatters && (
                    <p className="text-[11px] text-on-surface-variant pl-6 italic">
                      Why this matters: {m.whyItMatters}
                    </p>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Section 7: Worked Problems & Step-by-Step Derivations */}
        {content.workedExamples && content.workedExamples.length > 0 && (
          <section id="sec-worked-examples" className="space-y-3 pt-4 border-t border-surface-container-high/40">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
              <span className="material-symbols-outlined text-secondary">calculate</span>
              Worked Examples &amp; Solutions
            </h2>
            <div className="space-y-4">
              {content.workedExamples.map((w, i) => (
                <div
                  key={i}
                  className="p-4 rounded-xl bg-surface-container-low border border-surface-container-high/60 space-y-3"
                >
                  <div className="font-semibold text-sm sm:text-base text-primary">
                    <span className="font-mono text-xs uppercase text-secondary mr-2">Problem {i + 1}:</span>
                    {w.problem}
                  </div>
                  <div className="space-y-1.5 pl-3 border-l-2 border-secondary/40 text-xs sm:text-sm text-on-surface">
                    {Array.isArray(w.stepByStepSolution) &&
                      w.stepByStepSolution.map((st, idx) => (
                        <p key={idx}>{st}</p>
                      ))}
                  </div>
                  {w.finalTakeaway && (
                    <div className="p-2.5 rounded-lg bg-surface-container-high/30 text-xs text-primary font-medium">
                      <span className="font-bold">Key Insight:</span> {w.finalTakeaway}
                    </div>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Section 8: Key Takeaways & Summary */}
        <section id="sec-summary" className="space-y-4 pt-4 border-t border-surface-container-high/40">
          <div className="p-5 rounded-2xl bg-secondary/5 border border-secondary/20 space-y-3">
            <h3 className="font-label-lg text-sm sm:text-base font-bold text-secondary uppercase tracking-wider flex items-center gap-2">
              <span className="material-symbols-outlined text-base">checklist</span>
              Core Syllabus Takeaways
            </h3>
            <ul className="space-y-2">
              {content.keyTakeaways.map((t, i) => (
                <li key={i} className="flex items-start gap-2 text-xs sm:text-sm text-on-surface">
                  <span className="material-symbols-outlined text-secondary text-sm mt-0.5 shrink-0">
                    check
                  </span>
                  <span>{t}</span>
                </li>
              ))}
            </ul>
          </div>

          <div className="p-4 rounded-xl bg-surface-container-low border border-surface-container-high/40 text-xs sm:text-sm text-on-surface-variant leading-relaxed">
            <span className="font-semibold text-primary block mb-1">Curriculum Synthesis:</span>
            {content.summary}
          </div>
        </section>

        {/* Section 9: Self-Assessment Diagnostics */}
        {content.selfAssessmentQuestions && content.selfAssessmentQuestions.length > 0 && (
          <section id="sec-assessment" className="space-y-3 pt-4 border-t border-surface-container-high/40 print:break-before-page">
            <h2 className="font-headline-md text-xl sm:text-2xl font-serif text-primary flex items-center gap-2">
              <span className="material-symbols-outlined text-secondary">quiz</span>
              Formative Self-Assessment
            </h2>
            <div className="space-y-3">
              {content.selfAssessmentQuestions.map((q, i) => {
                const isRevealed = revealedAnswers[q.id || `q-${i}`];
                return (
                  <div
                    key={q.id || i}
                    className="p-4 rounded-xl bg-surface-container-lowest border border-surface-container-high/60 space-y-2"
                  >
                    <div className="flex items-start justify-between gap-2">
                      <p className="font-semibold text-xs sm:text-sm text-primary">
                        <span className="font-mono text-xs text-on-surface-variant mr-1">Q{i + 1}.</span>
                        {q.question}
                      </p>
                      <button
                        type="button"
                        onClick={() => toggleAnswer(q.id || `q-${i}`)}
                        className="px-2.5 py-1 rounded bg-primary/10 hover:bg-primary/20 text-primary font-semibold text-xs transition-colors shrink-0 print:hidden"
                      >
                        {isRevealed ? "Hide Answer" : "Reveal Answer"}
                      </button>
                    </div>

                    {q.options && q.options.length > 0 && (
                      <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 pt-1">
                        {q.options.map((opt, oIdx) => (
                          <div
                            key={oIdx}
                            className="p-2 rounded bg-surface-container-low text-xs text-on-surface font-mono"
                          >
                            {opt}
                          </div>
                        ))}
                      </div>
                    )}

                    {(isRevealed || typeof window === "undefined") && (
                      <div className="mt-2 p-3 rounded-lg bg-emerald-500/10 border border-emerald-500/20 text-xs space-y-1">
                        <p className="font-bold text-emerald-700 dark:text-emerald-400">
                          Correct Answer: {q.correctAnswer}
                        </p>
                        <p className="text-on-surface">{q.explanation}</p>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          </section>
        )}

        {/* Section 10: Further Reading & Academic Provenance */}
        <footer className="pt-6 border-t border-surface-container-high/60 space-y-3 text-xs text-on-surface-variant">
          <div className="p-4 rounded-xl bg-surface-container-low border border-surface-container-high/40 flex items-center justify-between gap-4 flex-wrap">
            <div className="space-y-0.5">
              <p className="font-semibold text-primary">Pencill Academic Provenance</p>
              <p>Generated by Pencill Academic Engine • Verified Syllabus Grounding</p>
            </div>
            <div className="font-mono text-[11px] text-on-surface-variant">
              Model: {document.generationModel}
            </div>
          </div>
        </footer>
      </div>
    </article>
  );
}
